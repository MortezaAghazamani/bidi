#!/usr/bin/env python3
"""
Generates the Arabic/Persian shaping table from ArabicShaping.txt.

Usage:
    python gen_arabic_persian_shaping.py ArabicShaping.txt output.inc

ArabicShaping.txt is available at:
    https://www.unicode.org/Public/UCD/latest/ucd/ArabicShaping.txt
"""

import sys


def parse_shaping(path):
    with open(path, 'r', encoding='utf-8') as f:
        for line in f:
            if '#' in line:
                line = line[:line.index('#')]
            line = line.strip()
            if not line:
                continue

            parts = [p.strip() for p in line.split(';')]
            if len(parts) < 4:
                continue

            cp = int(parts[0], 16)
            joining_type = parts[2]  # R, L, D, C, U, T

            if joining_type not in ('R', 'L', 'D', 'C', 'U', 'T'):
                continue

            yield cp, joining_type


def emit(entries, out):
    out.write("    // Generated by tools/gen_arabic_persian_shaping.py "
              "from ArabicShaping.txt.\n")
    out.write("    // Sorted by code point. Do not edit by hand.\n")
    for cp, jt in entries:
        out.write(f"    {{ 0x{cp:04X}, '{jt}' }},\n")


def main():
    if len(sys.argv) != 3:
        print(f"Usage: {sys.argv[0]} ArabicShaping.txt output.inc",
              file=sys.stderr)
        sys.exit(1)

    entries = sorted(parse_shaping(sys.argv[1]), key=lambda e: e[0])

    with open(sys.argv[2], 'w', encoding='utf-8', newline='\n') as out:
        emit(entries, out)


if __name__ == '__main__':
    main()
