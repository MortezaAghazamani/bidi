#!/usr/bin/env python3
"""
Generates the mirroring table from BidiMirroring.txt.

Usage:
    python gen_bidi_mirroring.py BidiMirroring.txt output.inc

BidiMirroring.txt is available at:
    https://www.unicode.org/Public/UCD/latest/ucd/BidiMirroring.txt
"""

import sys


def parse_mirroring(path):
    with open(path, 'r', encoding='utf-8') as f:
        for line in f:
            if '#' in line:
                line = line[:line.index('#')]
            line = line.strip()
            if not line:
                continue
            parts = line.split(';')
            if len(parts) != 2:
                continue
            cp = int(parts[0].strip(), 16)
            mirror = int(parts[1].strip(), 16)
            yield cp, mirror


def emit(entries, out):
    out.write("    // Generated by tools/gen_bidi_mirroring.py from BidiMirroring.txt.\n")
    out.write("    // Sorted by code point. Do not edit by hand.\n")
    for cp, mirror in entries:
        out.write(f"    {{ 0x{cp:04X}, 0x{mirror:04X} }},\n")


def main():
    if len(sys.argv) != 3:
        print(f"Usage: {sys.argv[1]} BidiMirroring.txt output.inc",
              file=sys.stderr)
        sys.exit(1)

    entries = sorted(parse_mirroring(sys.argv[1]), key=lambda e: e[0])

    with open(sys.argv[2], 'w', encoding='utf-8', newline='\n') as out:
        emit(entries, out)


if __name__ == '__main__':
    main()
