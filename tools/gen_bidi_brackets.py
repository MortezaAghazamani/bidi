#!/usr/bin/env python3
"""
Generates the bracket table from BidiBrackets.txt.

Usage:
    python gen_bidi_brackets.py BidiBrackets.txt output.inc

BidiBrackets.txt is available at:
    https://www.unicode.org/Public/UCD/latest/ucd/BidiBrackets.txt
"""

import sys


def parse_brackets(path):
    with open(path, 'r', encoding='utf-8') as f:
        for line in f:
            if '#' in line:
                line = line[:line.index('#')]
            line = line.strip()
            if not line:
                continue

            parts = line.split(';')
            if len(parts) != 3:
                continue

            cp = int(parts[0].strip(), 16)
            paired = int(parts[1].strip(), 16)
            btype = parts[2].strip()

            if btype == 'o':
                kind = 'Open'
            elif btype == 'c':
                kind = 'Close'
            else:
                continue

            yield cp, paired, kind


def emit(entries, out):
    out.write("    // Generated by tools/gen_bidi_brackets.py from BidiBrackets.txt.\n")
    out.write("    // Sorted by code point. Do not edit by hand.\n")
    for cp, paired, kind in entries:
        out.write(f"    {{ 0x{cp:04X}, 0x{paired:04X}, BracketType::{kind} }},\n")


def main():
    if len(sys.argv) != 3:
        print(f"Usage: {sys.argv[0]} BidiBrackets.txt output.inc", file=sys.stderr)
        sys.exit(1)

    entries = sorted(parse_brackets(sys.argv[1]), key=lambda e: e[0])

    with open(sys.argv[2], 'w', encoding='utf-8', newline='\n') as out:
        emit(entries, out)


if __name__ == '__main__':
    main()
