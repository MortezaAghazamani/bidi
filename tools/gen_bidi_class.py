#!/usr/bin/env python3
"""
Generates a compact range-based Bidi_Class table from UnicodeData.txt.

Usage:
    python gen_bidi_class.py UnicodeData.txt <output.inc>

The output is a C++ initializer list of Range entries, sorted by start.
UnicodeData.txt is available at:
    https://www.unicode.org/Public/UCD/latest/ucd/UnicodeData.txt
"""

import sys

BIDI_CLASS_MAP = {
    'L':   'L',
    'R':   'R',
    'AL':  'AL',
    'EN':  'EN',
    'ES':  'ES',
    'ET':  'ET',
    'AN':  'AN',
    'CS':  'CS',
    'NSM': 'NSM',
    'BN':  'BN',
    'B':   'B',
    'S':   'S',
    'WS':  'WS',
    'ON':  'ON',
    'LRE': 'LRE',
    'RLE': 'RLE',
    'PDF': 'PDF',
    'LRO': 'LRO',
    'RLO': 'RLO',
    'LRI': 'LRI',
    'RLI': 'RLI',
    'FSI': 'FSI',
    'PDI': 'PDI',
}


def parse_unicode_data(path):
    with open(path, 'r', encoding='utf-8') as f:
        for line in f:
            line = line.rstrip('\n')
            if not line:
                continue
            fields = line.split(';')
            if len(fields) < 5:
                continue
            cp = int(fields[0], 16)
            bidi = fields[4].strip()
            if not bidi:
                bidi = 'L'
            if bidi not in BIDI_CLASS_MAP:
                continue
            yield cp, BIDI_CLASS_MAP[bidi]


def build_ranges(entries):
    ranges = []
    current_start = None
    current_end = None
    current_class = None

    for cp, cls in entries:
        if current_class is None:
            current_start = cp
            current_end = cp
            current_class = cls
        elif cls == current_class and cp == current_end + 1:
            current_end = cp
        else:
            ranges.append((current_start, current_end, current_class))
            current_start = cp
            current_end = cp
            current_class = cls

    if current_class is not None:
        ranges.append((current_start, current_end, current_class))

    return ranges


def emit(ranges, out):
    out.write("    // Generated by tools/gen_bidi_class.py from UnicodeData.txt.\n")
    out.write("    // Sorted by start code point. Do not edit by hand.\n")
    for start, end, cls in ranges:
        out.write(f"    {{ 0x{start:04X}, 0x{end:04X}, BidiClass::{cls} }},\n")


def main():
    if len(sys.argv) != 3:
        print(f"Usage: {sys.argv[0]} UnicodeData.txt output.inc", file=sys.stderr)
        sys.exit(1)

    entries = list(parse_unicode_data(sys.argv[1]))
    entries.sort(key=lambda e: e[0])
    ranges = build_ranges(entries)

    with open(sys.argv[2], 'w', encoding='utf-8', newline='\n') as out:
        emit(ranges, out)


if __name__ == '__main__':
    main()
